/**
 * TypeScript types for the Pesapal v3 API (API 3.0 - JSON).
 * Reference: https://developer.pesapal.com/how-to-integrate/e-commerce/api-30-json/
 *
 * Only the v3 (JSON) endpoints are modelled here. v2 (XML) is intentionally
 * excluded as it is deprecated.
 */

export type PesapalEnv = "sandbox" | "production";

/**
 * Pesapal token returned by POST /api/Auth/RequestToken.
 * Tokens are valid for ~5 minutes.
 */
export interface PesapalTokenResponse {
  token: string;
  /** ISO-8601 UTC timestamp, e.g. "2026-08-26T12:29:30.5177702Z" */
  expiryDate: string;
  /** Pesapal error object, or null on success */
  error: PesapalErrorObject | null;
  /** Response code, "200" on success */
  status: string;
  /** Human readable message */
  message: string;
}

export interface PesapalErrorObject {
  error_type?: string;
  code?: string | number;
  message?: string;
  call_back_url?: string;
}

/**
 * Pesapal IPN registration response (POST /api/URLSetup/RegisterIPN).
 */
export interface PesapalIPNResponse {
  url: string;
  created_date: string;
  /** GUID uniquely identifying the registered IPN endpoint */
  ipn_id: string;
  notification_type: number;
  ipn_notification_type_description: string;
  ipn_status: number;
  ipn_status_description: string;
  error: PesapalErrorObject | null;
  status: string;
}

/** Customer billing address object accepted by Pesapal submitOrder. */
export interface PesapalBillingAddress {
  email_address?: string;
  /** E.164 or local Kenyan format, e.g. +254712345678 or 0712345678 */
  phone_number?: string;
  country_code?: string;
  first_name?: string;
  middle_name?: string;
  last_name?: string;
  line_1?: string;
  line_2?: string;
  city?: string;
  state?: string;
  postal_code?: string | null;
  zip_code?: string | null;
}

/**
 * Request body for POST /api/Transactions/SubmitOrderRequest.
 */
export interface PesapalSubmitOrderRequest {
  /** Merchant-generated unique reference (<=50 chars; alnum, -, _, ., :) */
  id: string;
  currency: string;
  amount: number | string;
  /** Max 100 chars */
  description: string;
  /** URL Pesapal redirects the customer's browser to after payment */
  callback_url: string;
  redirect_mode?: "TOP_WINDOW" | "PARENT_WINDOW";
  cancellation_url?: string;
  /** IPN id returned by RegisterIPNURL */
  notification_id: string;
  branch?: string;
  billing_address: PesapalBillingAddress;
}

/**
 * Response body from POST /api/Transactions/SubmitOrderRequest.
 */
export interface PesapalSubmitOrderResponse {
  /** Unique order id generated by Pesapal */
  order_tracking_id: string;
  /** Merchant's reference echoed back */
  merchant_reference: string;
  /** Hosted payment URL the customer is redirected to */
  redirect_url: string;
  error: PesapalErrorObject | null;
  status: string;
}

/**
 * Response body from GET /api/Transactions/GetTransactionStatus.
 */
export interface PesapalTransactionStatusResponse {
  payment_method: string;
  amount: number | string;
  created_date: string;
  confirmation_code: string;
  /** INVALID | COMPLETED | FAILED | REVERSED (case as returned by Pesapal) */
  payment_status_description: string;
  description: string;
  message: string;
  payment_account: string;
  call_back_url: string;
  /** 0 INVALID | 1 COMPLETED | 2 FAILED | 3 REVERSED */
  status_code: number;
  merchant_reference: string;
  currency: string;
  error: PesapalErrorObject | null;
  status: string;
}

/**
 * Normalised order status stored in the local database.
 * Maps 1:1 to Pesapal payment_status_description (lower-cased).
 */
export type PesapalOrderStatus =
  | "pending"
  | "completed"
  | "failed"
  | "reversed"
  | "invalid";

/** Raw fields delivered to both the IPN and the browser callback. */
export interface PesapalCallbackParams {
  OrderTrackingId?: string;
  OrderMerchantReference?: string;
  OrderNotificationType?: string;
}
